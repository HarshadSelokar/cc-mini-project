// =============================================================================
//  Lexer.cpp  --  Phase 1: Lexical analysis (driver around the Flex scanner)
// -----------------------------------------------------------------------------
//  Runs the Flex-generated DFA over the whole source file and collects the
//  tokens into a vector.  It also performs the one check that regular
//  expressions cannot express conveniently: integer literals must fit into
//  a 32-bit signed integer (LLVM type i32).
// =============================================================================
#include "Lexer.h"
#include "parser.tab.hpp"   // token codes generated by Bison

#include <iomanip>
#include <ostream>

namespace minilang {

namespace detail {
ScanState scanState;
}

std::string tokenName(int kind) {
    switch (kind) {
    case 0:              return "EOF";
    case TOK_LET:        return "LET";
    case TOK_IF:         return "IF";
    case TOK_ELSE:       return "ELSE";
    case TOK_WHILE:      return "WHILE";
    case TOK_PRINT:      return "PRINT";
    case TOK_TRUE:       return "TRUE";
    case TOK_FALSE:      return "FALSE";
    case TOK_IDENTIFIER: return "IDENTIFIER";
    case TOK_NUMBER:     return "NUMBER";
    case TOK_PLUS:       return "PLUS";
    case TOK_MINUS:      return "MINUS";
    case TOK_MUL:        return "MUL";
    case TOK_DIV:        return "DIV";
    case TOK_MOD:        return "MOD";
    case TOK_ASSIGN:     return "ASSIGN";
    case TOK_EQ:         return "EQ";
    case TOK_NE:         return "NE";
    case TOK_LT:         return "LT";
    case TOK_GT:         return "GT";
    case TOK_LE:         return "LE";
    case TOK_GE:         return "GE";
    case TOK_AND:        return "AND";
    case TOK_OR:         return "OR";
    case TOK_NOT:        return "NOT";
    case TOK_LPAREN:     return "LPAREN";
    case TOK_RPAREN:     return "RPAREN";
    case TOK_LBRACE:     return "LBRACE";
    case TOK_RBRACE:     return "RBRACE";
    case TOK_SEMICOLON:  return "SEMICOLON";
    default:             return "UNKNOWN";
    }
}

Lexer::Lexer(const std::string& source, Diagnostics& diagnostics)
    : source_(source), diag_(diagnostics) {}

std::vector<Token> Lexer::tokenize() {
    using namespace detail;
    scanState = ScanState{};
    scanState.diag = &diag_;

    std::vector<Token> tokens;
    scannerBegin(source_);
    while (int kind = scannerNext()) {
        Token tok{kind, scannerText(), SourceLoc{scanState.tokenLine, scanState.tokenColumn}};

        if (kind == TOK_NUMBER) {
            // The pattern guarantees digits only; check the i32 range here.
            long long value = 0;
            bool overflow = false;
            for (char c : tok.lexeme) {
                value = value * 10 + (c - '0');
                if (value > 2147483647LL) { overflow = true; break; }
            }
            if (overflow) {
                diag_.error(Phase::Lexer, tok.loc,
                            "integer literal '" + tok.lexeme + "' is too large (maximum is 2147483647)");
                continue;
            }
        }
        tokens.push_back(std::move(tok));
    }
    scannerEnd();

    tokens.push_back(Token{0, "", SourceLoc{scanState.line, scanState.column}});
    return tokens;
}

void Lexer::printTokens(const std::vector<Token>& tokens, std::ostream& out) {
    out << std::left << std::setw(10) << "LINE:COL" << std::setw(14) << "TOKEN" << "LEXEME\n";
    out << std::string(36, '-') << '\n';
    for (const Token& t : tokens) {
        std::string pos = std::to_string(t.loc.line) + ":" + std::to_string(t.loc.column);
        out << std::setw(10) << pos << std::setw(14) << tokenName(t.kind) << t.lexeme << '\n';
    }
    out << std::right;

    // Compact form: one row of token names per source line.
    out << "\nToken stream (" << tokens.size() << " tokens):\n";
    int line = -1;
    for (const Token& t : tokens) {
        if (t.loc.line != line) {
            if (line != -1) out << '\n';
            line = t.loc.line;
            out << "  ";
        } else {
            out << ' ';
        }
        out << tokenName(t.kind);
    }
    out << '\n';
}

} // namespace minilang
